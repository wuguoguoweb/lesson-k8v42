export const lessons=[];
const previous=new Map(),counts=Array(10).fill(0);
export function lessonCode(l,scripts,marked=false){
 if(l.script===undefined)return '';
 const source=scripts[l.script].code.split('\n');
 return l.lines.map(i=>source[i]+(marked&&l.added.includes(i)&&source[i]!=='結束'?' // ★ 新增':'')).join('\n');
}
function step(stage,title,target,actions,check,options={}){
 const l={id:`${stage+1}-${++counts[stage]}`,stage,title,target,actions,check,...options};
 if(l.script!==undefined){
  const old=previous.get(l.script);l.lines=[...new Set(l.lines)].sort((a,b)=>a-b);
  l.added=l.lines.filter(i=>!old?.lines.includes(i));
  if(old)l.back=`回到第 ${old.id} 步的${l.script===4?'移動':l.script===5?'動畫':'這段'}程式；依星號位置加入。`;
  previous.set(l.script,l);
 }
 lessons.push(l);return l;
}
